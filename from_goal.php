    document.addEventListener("DOMContentLoaded", function () {

        const carousel_t = document.querySelector(".table_div_carosuel");
        const cards_t = carousel_t.querySelectorAll(".table_divt");
        const dots_t = document.querySelectorAll(".carousel_dot_t");

        function updateDots_t() {

            let closestIndex_t = 0;
            let closestDistance_t = Infinity;

            cards_t.forEach(function (card_t, index_t) {

                const distance_t = Math.abs(
                    card_t.offsetLeft - carousel_t.scrollLeft
                );

                if (distance_t < closestDistance_t) {
                    closestDistance_t = distance_t;
                    closestIndex_t = index_t;
                }

            });

            dots_t.forEach(function (dot_t, index_t) {
                dot_t.classList.toggle(
                    "active_t",
                    index_t === closestIndex_t
                );
            });
        }

        carousel_t.addEventListener("scroll", updateDots_t);

        updateDots_t();

    });
</script>

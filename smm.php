<script>
  document.addEventListener("DOMContentLoaded", function () {

    const slider = document.querySelector(".seo_essentials_cards");
    const cards = document.querySelectorAll(".seo_essential_card");
    const dots = document.querySelectorAll(".seo_essentials_dots button");

    if (!slider || !cards.length || !dots.length) {
      return;
    }

    dots.forEach((dot, index) => {

      dot.addEventListener("click", function () {

        const card = cards[index];

        if (!card) {
          return;
        }

        slider.scrollTo({
          left: card.offsetLeft - slider.offsetLeft,
          behavior: "smooth"
        });

        dots.forEach(item => {
          item.classList.remove("active");
        });

        dot.classList.add("active");
      });

    });


    /* Update active dot while manually swiping */

    slider.addEventListener("scroll", function () {

      let closestIndex = 0;
      let closestDistance = Infinity;

      cards.forEach((card, index) => {

        const distance = Math.abs(
          card.offsetLeft - slider.scrollLeft
        );

        if (distance < closestDistance) {
          closestDistance = distance;
          closestIndex = index;
        }

      });

      dots.forEach(item => {
        item.classList.remove("active");
      });

      if (dots[closestIndex]) {
        dots[closestIndex].classList.add("active");
      }

    });

  });
</script>
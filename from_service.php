<script>
    document.addEventListener('DOMContentLoaded', function () {

        const dropdowns_t = document.querySelectorAll('.dropdown_t');

        dropdowns_t.forEach(function (dropdown_t) {

            const button_t = dropdown_t.querySelector('.dropdown_button_t');
            const menu_t = dropdown_t.querySelector('.dropdown_menu_t');
            const text_t = dropdown_t.querySelector('.dropdown_text_t');
            const arrow_t = dropdown_t.querySelector('.dropdown_arrow_t');
            const options_t = dropdown_t.querySelectorAll('.dropdown_option_t');

            button_t.addEventListener('click', function (event_t) {
                event_t.stopPropagation();

                menu_t.classList.toggle('active_t');
                arrow_t.classList.toggle('rotate_t');
            });

            options_t.forEach(function (option_t) {
                option_t.addEventListener('click', function () {

                    text_t.textContent = this.textContent;

                    menu_t.classList.remove('active_t');
                    arrow_t.classList.remove('rotate_t');
                });
            });
        });

        document.addEventListener('click', function () {
            dropdowns_t.forEach(function (dropdown_t) {

                const menu_t = dropdown_t.querySelector('.dropdown_menu_t');
                const arrow_t = dropdown_t.querySelector('.dropdown_arrow_t');

                menu_t.classList.remove('active_t');
                arrow_t.classList.remove('rotate_t');

            });
        });

    });
</script>
<script>
    $(document).ready(function () {

        // Handle clicks anywhere on the service card
        $(document).on("click", ".single_services_cardt", function (e) {

            // Ignore direct checkbox clicks because they toggle automatically
            if ($(e.target).closest(".check_boxttt").length) {
                return;
            }

            // Do not toggle the card when clicking Find out more
            if ($(e.target).closest(".button_arrow_div p").length) {
                return;
            }

            let card = $(this);
            let checkbox = card.find(".check_boxttt");

            checkbox.prop("checked", !checkbox.prop("checked"));
            checkbox.trigger("change");
        });

        // Update card and button when checkbox changes
        $(document).on("change", ".check_boxttt", function () {

            let card = $(this).closest(".single_services_cardt");
            let button = card.find(".diff_widtht");

            if (this.checked) {
                card.addClass("selected_servicet");
                button.text("Selected");
            } else {
                card.removeClass("selected_servicet");
                button.text("Add");
            }
        });

    });
</script>